/* custom: 사용자가 직접 적었던 종목 이름. 기본 목록보다 먼저 추천한다. */
export function filterExercises(query, custom = []) {
  if (!query?.trim()) return [];
  const q = query.toLowerCase().replace(/\s/g, '');
  const seen = new Set();
  const hits = [];
  // 내가 적었던 이름이 항상 기본 목록보다 먼저 나온다. 같은 묶음 안에서는 앞부분이 맞는 이름이 먼저다
  [[custom, 0], [EXERCISES, 1]].forEach(([list, group]) => {
    list.forEach((name, order) => {
      const key = String(name).toLowerCase().replace(/\s/g, '');
      if (!key.includes(q) || seen.has(key)) return;
      seen.add(key);
      hits.push({ name, rank: group * 2 + (key.startsWith(q) ? 0 : 1), order });
    });
  });
  return hits.sort((a, b) => a.rank - b.rank || a.order - b.order).slice(0, 10).map(hit => hit.name);
}

export function filterBodyParts(query) {
  if (!query?.trim()) return BODY_PARTS;
  const q = query.toLowerCase();
  return BODY_PARTS.filter(p => p.includes(q));
}
