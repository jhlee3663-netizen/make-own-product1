export const translations: Record<Lang, Dict> = { ko, en };

const LANG_KEY = 'smart-pin-lang';

export function getInitialLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'ko' || saved === 'en') return saved;
  } catch (_) {}
  return 'ko';
}

export function persistLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch (_) {}
}

export function t(lang: Lang, key: string, ...args: any[]): string {
  const v = translations[lang][key];
  return typeof v === 'function' ? (v as (...a: any[]) => string)(...args) : (v as string);
}
